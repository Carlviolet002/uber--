CREATE TABLE IF NOT EXISTS t_shop (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(64) NOT NULL,
  address VARCHAR(255) NOT NULL,
  lng DOUBLE NOT NULL,
  lat DOUBLE NOT NULL,
  phone VARCHAR(16),
  status TINYINT NOT NULL DEFAULT 0,
  owner_user_id BIGINT,
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
  update_time DATETIME DEFAULT CURRENT_TIMESTAMP,
  deleted TINYINT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS t_category (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  shop_id BIGINT NOT NULL,
  name VARCHAR(64) NOT NULL,
  sort INT NOT NULL DEFAULT 0,
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
  update_time DATETIME DEFAULT CURRENT_TIMESTAMP,
  deleted TINYINT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS t_dish (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  shop_id BIGINT NOT NULL,
  category_id BIGINT NOT NULL,
  name VARCHAR(64) NOT NULL,
  price DECIMAL(10,2) NOT NULL,
  image VARCHAR(255),
  status TINYINT NOT NULL DEFAULT 0,
  sold_out TINYINT NOT NULL DEFAULT 0,
  create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
  update_time DATETIME DEFAULT CURRENT_TIMESTAMP,
  deleted TINYINT NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_category_shop ON t_category (shop_id);
CREATE INDEX IF NOT EXISTS idx_shop_id ON t_dish (shop_id);
CREATE INDEX IF NOT EXISTS idx_category_id ON t_dish (category_id);
